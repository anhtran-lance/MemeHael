const D = (d) => '2026-10-' + d;

const ph = (id, name) => ({ id, type: 'phase', name });
const gr = (id, name) => ({ id, type: 'group', name });
function tk(id, theme, name, owner, role, solution, priority, s, e, mark, scope, deliverable, accept, dep, status, extra) {
  return Object.assign({
    id, type: 'task', theme, name, owner, role, solution, priority,
    start: D(s), end: D(e), mark, scope, deliverable, accept, dep: dep || '',
    status: status || 'todo', note: '', milestone: false,
  }, extra || {});
}

